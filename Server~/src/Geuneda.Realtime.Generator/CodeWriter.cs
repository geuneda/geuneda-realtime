using System.Text;

namespace Geuneda.Realtime.Generator
{
	/// <summary>
	/// 들여쓰기(탭)를 관리하는 생성 코드 작성기입니다.
	/// </summary>
	internal sealed class CodeWriter
	{
		private readonly StringBuilder _builder = new StringBuilder();
		private int _indent;

		public CodeWriter Line(string text = "")
		{
			if (text.Length > 0)
			{
				_builder.Append('\t', _indent);
			}

			_builder.Append(text).Append('\n');
			return this;
		}

		public CodeWriter Open(string text)
		{
			Line(text);
			Line("{");
			_indent++;
			return this;
		}

		public CodeWriter Close(string suffix = "")
		{
			_indent--;
			return Line("}" + suffix);
		}

		public CodeWriter Header()
		{
			return Line("// <auto-generated>Geuneda.Realtime.Generator 가 [RpcService] 계약으로 만든 코드입니다. 고치지 마세요.</auto-generated>")
				.Line("#nullable disable")
				.Line("#pragma warning disable")
				.Line();
		}

		public override string ToString()
		{
			return _builder.ToString();
		}
	}
}
